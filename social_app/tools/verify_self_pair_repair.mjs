await assert.rejects(changed.db.exec(repair));await changed.db.exec('rollback');
assert.equal((await changed.db.query('select count(*)::integer as n from public.messages')).rows[0].n,2);
assert.equal((await changed.db.query('select count(*)::integer as n from public.conversations')).rows[0].n,2);
assert.equal((await changed.db.query("select to_regclass('public.app_repair_archive') as name")).rows[0].name,null);
console.log('PASS a new self-message aborts repair atomically and preserves all history');
