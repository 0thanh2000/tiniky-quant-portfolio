import fs from 'node:fs';
import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
import {isAbsolute} from 'node:path';
const modulePath=process.env.PGLITE_MODULE;
const {PGlite}=await import(modulePath && isAbsolute(modulePath) ? pathToFileURL(modulePath).href : modulePath || '@electric-sql/pglite');
const root=new URL('../',import.meta.url);
const fixture=fs.readFileSync(new URL('tools/fixtures/supabase_export_20261014.sql',root),'utf8');
const repair=fs.readFileSync(new URL('supabase/SUA_HAI_BAN_GHI_TU_KET_NOI.sql',root),'utf8');
const a='20000000-0000-0000-0000-000000000001',b='20000000-0000-0000-0000-000000000002';
async function setup(){
 const db=new PGlite();await db.exec(fixture);
 await db.query(`insert into auth.users(id,raw_user_meta_data) values($1,'{"username":"A"}'),($2,'{"username":"B"}')`,[a,b]);
 const self=(await db.query('insert into public.conversations(user1,user2) values($1,$1) returning id',[a])).rows[0].id;
 const valid=(await db.query('insert into public.conversations(user1,user2) values($1,$2) returning id',[a,b])).rows[0].id;
 await db.query("insert into public.friendships(user_id,friend_id,status) values($1,$1,'accepted'),($1,$2,'pending')",[a,b]);
 await db.query("insert into public.messages(conversation_id,sender_id,content) values($1,$2,'Keep this history')",[valid,a]);
 return {db,self,valid};
}
const {db,self,valid}=await setup();
await db.exec(repair);
assert.equal((await db.query('select count(*)::integer as n from public.app_repair_archive')).rows[0].n,2);
assert.equal((await db.query('select id from public.conversations')).rows[0].id,valid);
assert.equal((await db.query('select content from public.messages')).rows[0].content,'Keep this history');
assert.equal((await db.query('select status from public.friendships')).rows[0].status,'pending');
const archived=(await db.query("select snapshot from public.app_repair_archive where source_table='conversations'")).rows[0].snapshot;
assert.equal(archived.id,self);assert.equal(archived.user1,a);assert.equal(archived.user2,a);
console.log('PASS archive exactly two invalid self-pairs, preserve valid relationships and messages');
await db.exec('set role authenticated');
await assert.rejects(db.exec('select * from public.app_repair_archive'));
await db.exec('reset role');
console.log('PASS backup is not readable by ordinary app users');
await assert.rejects(db.exec(repair));await db.exec('rollback');
assert.equal((await db.query('select count(*)::integer as n from public.app_repair_archive')).rows[0].n,2);
console.log('PASS repeated repair stops without deleting additional records');
const counts=(await db.query(fs.readFileSync(new URL('supabase/KIEM_TRA_TRUOC.sql',root),'utf8'))).rows;
assert.ok(counts.every(row=>Number(row.issue_count)===0));
await db.exec(fs.readFileSync(new URL('supabase/INSTALLER_SQL_EDITOR.sql',root),'utf8'));
